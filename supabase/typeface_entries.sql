create or replace function public.reject_typeface_blocked_terms()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if public.typeface_sentence_has_blocked_terms(new.sentence) then
    raise exception using
      errcode = 'P0001',
      message = 'TYPEFACE_BLOCKED_TERM';
  end if;

  return new;
end;
$$;

